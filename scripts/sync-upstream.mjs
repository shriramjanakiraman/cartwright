#!/usr/bin/env node
// Door A, step 2: mirror official skills into upstream/ at exactly the versions pinned in upstream.lock.json.
// The mirror is read-only: files are copied unmodified (with each publisher's LICENSE), never hand-edited,
// and only ever changed by re-running this script after the lock moves.
//
// Usage: node scripts/sync-upstream.mjs           # rewrite upstream/ from the lock
//        node scripts/sync-upstream.mjs --check   # CI: fail if upstream/ differs from the pinned sources
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { ROOT, loadLock } from './lib.mjs';

const check = process.argv.includes('--check');
const UP = join(ROOT, 'upstream');
const lock = loadLock();
const work = mkdtempSync(join(tmpdir(), 'agent-skills-up-'));
const staging = join(work, 'upstream');
mkdirSync(staging, { recursive: true });

function refOf(src) {
  if (src.type === 'github-release') return `${src.tagPrefix || ''}${src.version}`;
  if (src.type === 'github-branch') return src.sha;
  return null;
}

function fetchTree(repo, ref) {
  const dir = join(work, repo.replace('/', '__'));
  if (existsSync(dir)) return dir;
  mkdirSync(dir, { recursive: true });
  const url = `https://codeload.github.com/${repo}/tar.gz/${encodeURIComponent(ref)}`;
  execFileSync('sh', ['-c', `curl -fsSL "${url}" | tar -xz -C "${dir}" --strip-components=1`], { stdio: 'inherit' });
  return dir;
}

function walk(dir, base = dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, base, out); else out.push(relative(base, p));
  }
  return out;
}

const manifest = { note: 'Generated by scripts/sync-upstream.mjs. Read-only mirror; do not edit.', sources: {} };
for (const [id, src] of Object.entries(lock.sources)) {
  if (!src.mirror) continue;
  const ref = refOf(src);
  const tree = fetchTree(src.repo, ref);
  const exclude = new Set(src.mirror.excludeSets || []);
  const entry = { repo: src.repo, ref, license: src.mirror.license, skills: {} };
  for (const rel of walk(tree)) {
    for (const rule of src.skillPaths || []) {
      const m = rel.match(new RegExp(rule.pattern));
      if (!m) continue;
      const set = rule.set || m[1];
      const name = rule.set ? m[1] : m[2];
      if (exclude.has(set)) continue;
      cpSync(join(tree, dirname(rel)), join(staging, id, name), { recursive: true });
      (entry.skills[set] ||= []).push(name);
    }
  }
  for (const f of ['LICENSE', 'LICENSE.txt', 'NOTICE', 'NOTICE.txt']) {
    if (existsSync(join(tree, f))) cpSync(join(tree, f), join(staging, id, f));
  }
  for (const k of Object.keys(entry.skills)) entry.skills[k].sort();
  manifest.sources[id] = entry;
}
// Upstream skills sometimes share a file through a relative symlink. Replace every symlink with a real
// copy of its target, so each mirrored skill folder works on its own.
(function materialize(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (lstatSync(p).isSymbolicLink()) {
      const real = realpathSync(p);
      const data = statSync(real).isFile() ? readFileSync(real) : null;
      rmSync(p, { force: true });
      if (data) writeFileSync(p, data); else cpSync(real, p, { recursive: true });
    } else if (lstatSync(p).isDirectory()) materialize(p);
  }
})(staging);
writeFileSync(join(staging, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

const count = Object.values(manifest.sources).reduce((n, s) => n + Object.values(s.skills).flat().length, 0);
if (check) {
  const a = existsSync(UP) ? walk(UP).sort() : [];
  const b = walk(staging).sort();
  const diff = [...new Set([...a, ...b])].filter((f) => {
    const pa = join(UP, f), pb = join(staging, f);
    return !existsSync(pa) || !existsSync(pb) || !readFileSync(pa).equals(readFileSync(pb));
  });
  rmSync(work, { recursive: true, force: true });
  if (diff.length) {
    console.error(`sync-upstream --check: upstream/ differs from the pinned sources (${diff.length} file(s)), e.g.\n  ${diff.slice(0, 10).join('\n  ')}\nRun "npm run sync-upstream" and commit.`);
    process.exit(1);
  }
  console.log(`sync-upstream --check: ${count} mirrored skill(s) match upstream.lock.json`);
} else {
  rmSync(UP, { recursive: true, force: true });
  cpSync(staging, UP, { recursive: true });
  rmSync(work, { recursive: true, force: true });
  console.log(`sync-upstream: mirrored ${count} official skill(s) into upstream/`);
}
